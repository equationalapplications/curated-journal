const { withAppBuildGradle } = require("@expo/config-plugins");

/**
 * Sideload release signing (specs/2026-11-06-sideload-signing-brand-followup,
 * R1 addendum 2026-11-06).
 *
 * The Expo SDK 58 template build.gradle signs release builds with the
 * PUBLIC debug keystore unconditionally — it has NO keystore.properties
 * wiring (EAS injects signing server-side, which is why store builds were
 * never affected; the original spec wrongly assumed template wiring
 * existed, and the first local 7.0.0 build produced a debug-signed
 * release APK). This plugin appends two blocks:
 *
 * - Signing wiring: when not on EAS and ../credentials/keystore.properties
 *   exists (parses, storeFile resolves), define signingConfigs.release from
 *   it and point buildTypes.release at it — local releases sign with the
 *   EAS upload keystore.
 * - Guard: when keystore.properties is missing (every fresh clone), fail
 *   any `*Release*` task loudly instead of silently extending the public
 *   debug-key lineage. Broken credentials (missing keys / missing
 *   storeFile) fail at configuration time.
 */
const GUARD = `
// Sideload release guard — specs/2026-11-06-sideload-signing-brand-followup
// Refuse release builds that would silently sign with the public debug
// keystore. EAS supplies its own keystore.properties during store builds,
// so this only fires on machines missing credentials/.
if (!System.getenv("EAS_BUILD") && !rootProject.file("../credentials/keystore.properties").exists()) {
    tasks.whenTaskAdded { task ->
        if (task.name.contains("Release")) {
            task.doFirst {
                throw new GradleException(
                    "Release build refused: ../credentials/keystore.properties is missing, so this build would be signed with the PUBLIC debug keystore. Restore credentials/ (see docs/VERSIONING.md) or build on EAS."
                )
            }
        }
    }
}
`;

const SIGNING_WIRING = `
// Sideload release signing wiring — R1 addendum (2026-11-06). The SDK 58
// template has NO keystore.properties wiring; without this block local
// release builds silently sign with the PUBLIC debug keystore even when
// credentials/ exists. EAS is exempt (its tooling injects upload-key
// signing); machines missing credentials/ are refused by the guard above.
if (!System.getenv("EAS_BUILD") && rootProject.file("../credentials/keystore.properties").exists()) {
    def sideloadKeystoreProps = new Properties()
    rootProject.file("../credentials/keystore.properties").withInputStream { sideloadKeystoreProps.load(it) }
    def sideloadMissing = ["storeFile", "storePassword", "keyAlias", "keyPassword"].findAll { !sideloadKeystoreProps[it] }
    if (!sideloadMissing.isEmpty()) {
        throw new GradleException("Release signing refused: ../credentials/keystore.properties lacks \${sideloadMissing.join(', ')} (docs/VERSIONING.md) — refusing to sign with the PUBLIC debug keystore.")
    }
    def sideloadStoreFile = rootProject.file(sideloadKeystoreProps['storeFile'])
    if (!sideloadStoreFile.exists()) {
        throw new GradleException("Release signing refused: storeFile resolves to missing \${sideloadStoreFile} (docs/VERSIONING.md) — refusing to sign with the PUBLIC debug keystore.")
    }
    android {
        signingConfigs {
            release {
                storeFile sideloadStoreFile
                storePassword sideloadKeystoreProps['storePassword']
                keyAlias sideloadKeystoreProps['keyAlias']
                keyPassword sideloadKeystoreProps['keyPassword']
            }
        }
        buildTypes {
            release {
                signingConfig = signingConfigs.release
            }
        }
    }
}
`;

const withSideloadReleaseGuard = (config) =>
  withAppBuildGradle(config, (mod) => {
    // Independent markers, so a tree generated by the pre-addendum plugin
    // (guard only) still gains the wiring on its next prebuild.
    if (!mod.modResults.contents.includes("Sideload release guard")) {
      mod.modResults.contents += GUARD;
    }
    if (!mod.modResults.contents.includes("Sideload release signing wiring")) {
      mod.modResults.contents += SIGNING_WIRING;
    }
    return mod;
  });

module.exports = withSideloadReleaseGuard;
